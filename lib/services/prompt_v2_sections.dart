      '历史栏不接受 `op=noChange`；需要合并时，按下面的合并指令在**同一次调用**里'
      '补 `op=set`。本回合不输出正文、不联网、不改世界状态 / 角色状态 / 当前时间。'
      '第一步若已读过历史，它的 `<memorySummary>` 结果就在上面，维护步重复读取'
      '会被拒绝；第一步漏读时才允许补读一次。';

  /// 维护回合的修复帧指令头（当前档位清单里只会出现历史）。
  static const String stateHeadFix = '[State-maintenance turn] 只修复下面列出的各项，'
      '只调工具、不要输出正文。锚点从对话里已有的历史结果块与失败回传的栏目全文'
      '中复制，实在定位不到才用 `op=reset` 整栏重写。只维护记忆总结，清单必须做完。';

  /// 工作副本里已经存在本轮条目时的维护补充行（避免模型重复 append）。
  static const String stateHeadEntryExists =
      '注意：历史栏里已经有本轮那一条了，**不要重复追加**；只检查格式与合并要求，'
      '缺合并就补 `op=set`。';

  /// 尚未落地的「记忆合并」指令行（维护步 / 修复清单共用）。
  static List<String> memoryMergeAgentLines(MemoryMergePlan? plan) {
    if (plan == null || !plan.hasAction) return const [];
    return [
      '- 【本轮记忆合并】每个区间一条 `op=set`：`before` = 该区间各轮条目原文'
          '（用 \\n 连接，从 `$kReadHistoryToolName` 的结果里逐字复制），'
          '`newLine` = 下面的合并行；随后照常 `op=append` 追加本轮条目，'
          '以上可以放在同一次调用里。',
      for (final r in plan.ranges)
        '  - 第 ${r.startRound}~${r.endRound} 轮（${r.roundCount} 条）'
            '合并为一行：`${memoryMergedEntryTemplate(
              startRound: r.startRound,
              endRound: r.endRound,
              startTime: r.startTime,
              endTime: r.endTime,
            )}`',
    ];
  }

  /// 维护回合清单一次最多下发的条数（与 v1 一致）。
  static const int maxStateProblems = 8;

  /// 清单项优先级（数值越小越靠前）：记忆 > 角色 > 世界 > 其他。
  ///
  /// 世界 / 角色的两档优先级**保留为框架**：当前档位只注册历史栏目，清单里
  /// 实际只会出现记忆与工具失败说明（后者归「其他」）。
  static int problemPriority(String line) {
    if (line.contains('memorySummary')) return 0;
    if (line.contains('characterState')) return 1;
    if (line.contains('worldState')) return 2;
    return 3;
  }

  /// 维护回合指令头（首回合 / 修复回合）。
  static String stateHead({required bool first}) =>
      first ? stateHeadLv1 : stateHeadFix;
